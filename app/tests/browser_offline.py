IMPORT_PATTERN = re.compile(r"((?:import\s+[^;\n]+?\s+from\s+)[\"'])([^\"']+)([\"'])")


def module_url(path: Path, cache: dict[Path, str]) -> str:
    """Create module URLs with absolute nested imports; no bundler is required."""
    path = path.resolve()
    if path in cache:
        return cache[path]

    def rewrite(match: re.Match) -> str:
        specifier = match.group(2)
        if not specifier.startswith("."):
            return match.group(0)
        return match.group(1) + module_url(path.parent / specifier, cache) + match.group(3)

    source = IMPORT_PATTERN.sub(rewrite, path.read_text())
    url = "data:text/javascript;base64," + base64.b64encode(source.encode()).decode()
    cache[path] = url
    return url


STUBS = """
(() => {
  const map = new Map();
  const store = {
    getItem: key => map.get(key) ?? null,
    setItem: (key, value) => map.set(key, String(value)),
    removeItem: key => map.delete(key),
  };
  Object.defineProperty(window, 'localStorage', {value: store, configurable: true});
  Object.defineProperty(window, 'sessionStorage', {value: store, configurable: true});
  window.sentMessages = [];
  window.WebSocket = class {
    static OPEN = 1;
    static CONNECTING = 0;
    constructor() { this.readyState = 0; this.listeners = {}; window.fakeWS = this; }
    addEventListener(name, listener) { this.listeners[name] = listener; }
    send(value) { window.sentMessages.push(JSON.parse(value)); }
  };
  window.pushSnapshot = (room) => window.fakeWS.listeners.message({
    data: JSON.stringify({type:'snapshot', room}),
  });
})();
"""


class Clock:
    def __init__(self):
        self.now = 100.0

    def __call__(self):
        return self.now

    def advance(self, seconds: float):
        self.now += seconds


def main():
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(
            headless=True,
            executable_path=os.getenv("CHROMIUM_PATH", "/usr/bin/chromium"),
            args=["--no-sandbox", "--no-proxy-server"],
        )
        page = browser.new_page(viewport={"width": 1440, "height": 900})
        errors = []
        page.on("pageerror", lambda error: errors.append(str(error)))
        css = "\n".join(["\n".join((WEB / "styles.css").read_text().splitlines()[1:]),
                         (WEB / "styles" / "typing.css").read_text(),
                         (WEB / "styles" / "speed.css").read_text()])
        page.set_content(
            f'<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1">'
            f'<style>{css}</style></head><body data-theme="station">'
            '<div class="grain"></div><div id="app"></div><div id="toast-layer"></div></body></html>',
            wait_until="domcontentloaded",
        )
        page.evaluate(STUBS)
        cache = {}
        result = page.evaluate(
            "url => import(url).then(() => 'ok').catch(error => String(error))",
            module_url(WEB / "app.js", cache),
        )
        assert result == "ok", result
        expect(page.locator(".mission-card")).to_have_count(6)
        expect(page.locator(".academy-card")).to_have_count(3)
        page.screenshot(path=str(OUT / "home-interactive-v04.png"), full_page=True, animations="disabled")

        # A real DOM keyboard drives all fourteen simulated Linux lessons.
        page.locator('[data-action="learn"][data-os="linux"]').click()
        expect(page.locator("#lesson-input")).to_be_visible()
        commands = page.evaluate(
            "url => import(url).then(mod => mod.LESSONS.linux.commands.map(item => item.text))",
            module_url(WEB / "ui" / "lessons.js", cache),
        )
        page.locator("#lesson-input").fill("wrong command")
        page.locator("#lesson-input").press("Enter")
        expect(page.locator("#training-feedback")).to_contain_text("Not quite")
        expect(page.locator("#lesson-input")).to_have_value("wrong command")
        for index, command in enumerate(commands):
            field = page.locator("#lesson-input")
            field.fill(command)
            field.press("Enter")
            expect(page.locator("#training-feedback")).to_contain_text("COMMAND RECOGNIZED")
            expect(page.locator(".sample-output")).to_contain_text("SIMULATED TERMINAL OUTPUT")
            if index == 0:
                expect(page.locator(".sample-output")).to_contain_text("/home/operator")
            page.locator('[data-action="training-next"]').click()
            if index < len(commands) - 1:
                expect(page.locator("#lesson-input")).to_be_visible()
        expect(page.locator(".training-complete")).to_be_visible()
        expect(page.locator(".glossary-grid article")).to_have_count(14)
        page.screenshot(path=str(OUT / "training-complete-interactive-v04.png"), full_page=True, animations="disabled")
        page.locator('[data-action="training-home"]').first.click()
        expect(page.locator(".academy-card")).to_have_count(3)
        expect(page.locator('[data-action="learn"][data-os="linux"]')).to_contain_text("COMPLETED")
        page.locator('[data-action="learn"][data-os="windows"]').click()
        expect(page.locator("#lesson-input")).to_be_visible()
        expect(page.locator(".reference-command")).to_contain_text("Get-Location")
        page.locator('[data-action="training-review"]').click()
        expect(page.locator(".glossary-grid article")).to_have_count(14)
        page.screenshot(path=str(OUT / "training-interactive-v04.png"), full_page=True, animations="disabled")
        page.locator('[data-action="training-home"]').first.click()
        print("PASS: real Chromium command learning UX, wrong entry, all 14 steps, completion, review")

        # The browser controller receives phase snapshots from the actual game engine.
        page.locator('[data-action="choose-mission"][data-mission="casefile"]').click()
        assert page.locator("body").get_attribute("data-theme") == "casefile"
        page.evaluate("() => { fakeWS.readyState = 1; fakeWS.listeners.open(); }")
        page.locator('[data-action="solo"]').first.click()
        assert page.evaluate("sentMessages.at(-1).type") == "create"
        assert page.evaluate("sentMessages.at(-1).mission") == "casefile"
        clock = Clock()
        engine = GameEngine(clock)
        room, host = engine.create("GHOST_01", "casefile", solo=True)
        page.evaluate("room => pushSnapshot(room)", engine.view(room, host))
        expect(page.locator(".lobby-heading")).to_be_visible()
        assert page.evaluate("sentMessages.at(-1).type") == "start"
        engine.start(room, host)
        page.evaluate("room => pushSnapshot(room)", engine.view(room, host))
        expect(page.locator(".briefing-page")).to_be_visible()
        expect(page.locator(".briefing-stations")).to_contain_text("YOUR ROLE")
        page.screenshot(path=str(OUT / "briefing-interactive-v04.png"), full_page=True, animations="disabled")
        page.locator('[data-action="ready"]').click()
        assert page.evaluate("sentMessages.at(-1).type") == "ready"
        engine.ready(room, host)
        page.evaluate("room => pushSnapshot(room)", engine.view(room, host))
        expect(page.locator("#deployment-count")).to_be_visible()
        clock.advance(10.1)
        engine.tick(room)
        page.evaluate("room => pushSnapshot(room)", engine.view(room, host))
        expect(page.locator("#task-input")).to_be_enabled()
        expect(page.locator("#current-objective")).to_contain_text("timeline")
        page.locator('[data-action="guide"]').click()
        expect(page.locator("#modal-title")).to_contain_text("KNOW YOUR ROLE")
        page.locator('[data-action="close-modal"]').last.click()
        page.screenshot(path=str(OUT / "mystery-interactive-v04.png"), full_page=True, animations="disabled")
        target = engine.view(room, host)["target"]
        page.locator("#task-input").fill(target["text"])
        assert page.evaluate("sentMessages.at(-1).type") == "submit"
        engine.submit(room, host, target["id"], target["text"])
        page.evaluate("room => pushSnapshot(room)", engine.view(room, host))
        expect(page.locator("#clue-list")).to_contain_text("ARCHIVE ENTRY")
        engine._finish(room, True)
        page.evaluate("room => pushSnapshot(room)", engine.view(room, host))
        expect(page.locator(".result-debrief")).to_be_visible()
        expect(page.locator(".result-evidence")).to_contain_text("ARCHIVE ENTRY")
        assert not errors, f"Chromium script exceptions: {errors}"
        print("PASS: live controller with engine snapshots, lobby → briefing → countdown → game → results")

        # Reproduce the server's final deduction in a real human-owned browser view.
        # The first member defends after the swap; the second is the investigator.
        duo, owner = engine.create("ANALYST", "casefile")
        _, investigator = engine.join(duo.code, "DETECTIVE")
        engine.start(duo, owner)
        engine.ready(duo, owner)
        engine.ready(duo, investigator)
        clock.advance(10.1)
        engine.tick(duo)
        duo.stage = 2
        duo.progress = 5
        duo.discoveries = ["ARCHIVE ENTRY: The door opened at 00:18 with a staff master key."]
        engine._begin_accusation(duo)
        page.evaluate("room => pushSnapshot(room)", engine.view(duo, investigator))
        expect(page.locator("#accusation-panel")).to_be_visible()
        expect(page.locator("#accusation-options button")).to_have_count(4)
        page.locator('[data-action="accuse"][data-suspect="pierce"]').click()
        assert page.evaluate("sentMessages.at(-1).type") == "accuse"
        assert page.evaluate("sentMessages.at(-1).suspect") == "pierce"
        engine.accuse(duo, investigator, "pierce")
        page.evaluate("room => pushSnapshot(room)", engine.view(duo, investigator))
        expect(page.locator("#accusation-attempts")).to_contain_text("1 ACCUSATION MADE")
        clock.advance(2.1)
        page.locator('[data-action="accuse"][data-suspect="vale"]').click()
        engine.accuse(duo, investigator, MISSIONS["casefile"]["culprit"])
        page.evaluate("room => pushSnapshot(room)", engine.view(duo, investigator))
        expect(page.locator("#accusation-panel")).to_be_hidden()
        expect(page.locator("#task-input")).to_be_enabled()
        assert not errors, f"Chromium script exceptions: {errors}"
        print("PASS: murder mystery suspect board, wrong accusation, correct deduction in Chromium")

        assert page.evaluate("document.documentElement.scrollWidth <= innerWidth + 1")
        browser.close()
    print("PASS: interactive Chromium smoke test, no JavaScript exceptions")


if __name__ == "__main__":
    main()
