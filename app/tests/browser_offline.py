"""Interactive Chromium smoke test when local URL navigation is unavailable.

The real browser controller and view modules run from data: module URLs. Only the
WebSocket transport is stubbed; snapshots are generated by the real Python
engine. This tests actual DOM events, learning steps and phase changes without
making false claims about testing a live browser-to-server connection.

Run: CHROMIUM_PATH=/usr/bin/chromium python tests/browser_offline.py
"""
