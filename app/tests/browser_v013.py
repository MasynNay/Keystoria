"""Optional Chromium check for v0.13 typography and story illustrations.

Renders the real application templates using snapshots generated by the Python
engine. The browser does not use live WebSockets; network integration is tested
separately by tests/test_api.py and tests/test_field_websocket.py.

Run with: python tests/browser_v013.py
Requires Node, Playwright and a local Chromium executable.
"""
from __future__ import annotations

import json
import os
import subprocess
import tempfile
from pathlib import Path

from playwright.sync_api import sync_playwright
from server.content import MISSIONS
from server.game import GameEngine

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs' / 'screenshots'


class Clock:
    def __init__(self): self.now = 100.0
    def __call__(self): return self.now
    def advance(self, value): self.now += value


def snapshots():
    results={}
    for mission in MISSIONS:
        clock=Clock()
        engine=GameEngine(clock)
        room,host=engine.create('TEST',mission,solo=True)
        engine.start(room,host)
        engine.ready(room,host)
        results[f'{mission}_countdown']=engine.view(room,host)
        clock.advance(10.1)
        engine.tick(room)
        assert room.phase=='armed',mission
        results[f'{mission}_armed']=engine.view(room,host)
        engine.launch(room,host)
        assert room.phase=='playing',mission
        results[mission]=engine.view(room,host)
    return results


def read_page(page,path):
    page.set_content(path.read_text(),wait_until='domcontentloaded',timeout=12000)
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'),path.name


def main():
    with tempfile.TemporaryDirectory(prefix='panic-v013-') as dirname:
        folder=Path(dirname)
        (folder/'state.json').write_text(json.dumps(snapshots()))
        subprocess.run(['node',str(ROOT/'tests/render_v013_fixtures.mjs')],
            check=True,env={**os.environ,'PANIC_V013_PREVIEW':str(folder)},cwd=ROOT)
        OUT.mkdir(parents=True,exist_ok=True)
        with sync_playwright() as playwright:
            browser=playwright.chromium.launch(headless=True,
                executable_path=os.getenv('CHROMIUM_PATH','/usr/bin/chromium'),
                args=['--no-sandbox','--no-proxy-server'])
            page=browser.new_page(viewport={'width':1440,'height':900})
            read_page(page,folder/'home.html')
            ids=page.locator('.mission-card .mission-cover-mark svg.mission-mark[data-mission-mark]').evaluate_all(
                '(nodes)=>nodes.map(n=>n.dataset.missionMark)')
            assert len(ids)==len(MISSIONS)==len(set(ids))==12
            page.locator('.operations').screenshot(path=str(OUT/'twelve-mission-icons-v014.png'),animations='disabled')
            read_page(page,folder/'countdown.html')
            assert page.locator('#deployment-count').text_content()=='10'
            assert len(page.locator('.deployment-story').inner_text())>80
            page.screenshot(path=str(OUT/'countdown-ten-v014.png'),animations='disabled')
            read_page(page,folder/'armed.html')
            assert page.locator('[data-action=launch]').count()==1
            page.screenshot(path=str(OUT/'ready-to-play-v014.png'),animations='disabled')
            for mission in MISSIONS:
                read_page(page,folder/f'{mission}.html')
                assert page.locator('.story-director').get_attribute('data-director-world')==mission
                assert page.locator('.story-vista').get_attribute('data-world-vista')==mission
                assert page.locator('.cinematic-closeup').count()==1
                scene=page.locator('#cinema-art').bounding_box()
                field=page.locator('#task-input').bounding_box()
                assert scene['x']<field['x'],mission
                assert field['y']+field['height']<=900,mission
                if mission in ('dead_air','abyss','carnival'):
                    page.screenshot(path=str(OUT/f'{mission}-animation-v014.png'),animations='disabled')
            browser.close()
            browser=playwright.chromium.launch(headless=True,
                executable_path=os.getenv('CHROMIUM_PATH','/usr/bin/chromium'),
                args=['--no-sandbox','--no-proxy-server'])
            mobile=browser.new_page(viewport={'width':390,'height':844})
            read_page(mobile,folder/'home.html')
            assert mobile.locator('.mission-card .mission-cover-mark svg.mission-mark').count()==12
            read_page(mobile,folder/'dead_air.html')
            assert mobile.locator('.story-director').count()==1
            browser.close()
    print('PASS: twelve distinct card marks, ten-second briefing, twelve story camera scenes, desktop/mobile overflow')


if __name__=='__main__':
    main()
